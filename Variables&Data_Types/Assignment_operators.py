#Assignment operators
num = 10
num += 15  # instead of num = num + 15, we use num += 15
print("num += 15:", num)
num -= 5   # instead of num = num - 5, we use num -= 5
print("num -= 5:", num)
num *= 2   # instead of num = num * 2, we use num *= 2
print("num *= 2:", num)
num /= 2   # instead of num = num / 2, we use num /= 2
print("num /= 2:", num)
num %= 3   # instead of num = num % 3, we use num %= 3
print("num %= 3:", num)
num **= 2  # instead of num = num ** 2, we use num **= 2
print("num **= 2:", num)

num = 10
num = num % 3
print("num = num % 3:", num)